import requests
import pandas as pd
import io

FIRMS_URL = "https://firms.modaps.eosdis.nasa.gov/api/area/csv"
OPEN_METEO_URL = "https://api.open-meteo.com/v1/forecast"

SRI_LANKA_BBOX = "79.5,5.7,82.0,10.0"

def get_actual_fire_detections(map_key, days=1):
    """
    Returns possible active fire hotspots detected by satellite.
    This is real-time fire DETECTION, not prediction.
    """
    url = f"{FIRMS_URL}/{map_key}/VIIRS_SNPP_NRT/{SRI_LANKA_BBOX}/{days}"
    response = requests.get(url, timeout=30)

    if response.status_code != 200 or "latitude" not in response.text:
        return pd.DataFrame()

    fires = pd.read_csv(io.StringIO(response.text))
    return fires

def get_live_weather(lat, lon, days=7):
    """
    Returns live and forecast weather for a Sri Lankan location.
    """
    params = {
        "latitude": lat,
        "longitude": lon,
        "daily": [
            "temperature_2m_max",
            "temperature_2m_min",
            "relative_humidity_2m_mean",
            "wind_speed_10m_max",
            "precipitation_sum"
        ],
        "timezone": "Asia/Colombo",
        "forecast_days": days
    }

    response = requests.get(OPEN_METEO_URL, params=params, timeout=30)
    response.raise_for_status()

    data = response.json()["daily"]

    weather = pd.DataFrame({
        "date": pd.to_datetime(data["time"]),
        "temp": data["temperature_2m_max"],
        "RH": data["relative_humidity_2m_mean"],
        "wind": data["wind_speed_10m_max"],
        "rain": data["precipitation_sum"]
    })

    return weather

def prepare_live_features(weather, features):
    """
    Converts live weather into the feature format required by the model.
    """
    weather["X"] = 5
    weather["Y"] = 5

    weather["FFMC"] = 101 - weather["RH"] - weather["rain"] * 5
    weather["DMC"] = weather["temp"] * 0.6 + (100 - weather["RH"]) * 0.3
    weather["DC"] = weather["temp"] * 1.2 + (100 - weather["RH"]) * 0.5
    weather["ISI"] = (weather["FFMC"] / 50) * (weather["wind"] / 10)

    for col in features:
        if col not in weather.columns:
            weather[col] = 0

    return weather

def predict_fire_risk(model, scaler, weather, features):
    X_live = weather[features]
    X_live_scaled = scaler.transform(X_live)

    weather["fire_probability"] = model.predict_proba(X_live_scaled)[:, 1]

    def risk_level(prob):
        if prob >= 0.75:
            return "Very High"
        elif prob >= 0.55:
            return "High"
        elif prob >= 0.35:
            return "Moderate"
        else:
            return "Low"

    weather["risk_level"] = weather["fire_probability"].apply(risk_level)
    return weather

